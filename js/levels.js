/*
 * Уровни строятся программно (builder), а не ASCII-картами: так проще
 * править геометрию и не ошибиться с шириной строк.
 *
 * Символы сетки:
 *  #  стена/пол          =  платформа (проходима снизу)   ^  шипы
 *  s  тень (укрытие)     a-e терминал                      A-E дверь терминала a-e
 *  1-5 лазер терминала a-e                                 !  импульсный лазер
 *  P  старт   @  точка восстановления   *  фрагмент данных   i  предмет
 *  g  дрон-страж   k  камера (на потолке)   B  Ядро ИИ   X  выход
 */
const LEVEL_H = 18;

function buildLevel(spec) {
  const W = spec.w, H = LEVEL_H;
  const g = [];
  for (let y = 0; y < H; y++) g.push(new Array(W).fill('.'));
  const items = [], hints = [];
  const inb = (x, y) => x >= 0 && y >= 0 && x < W && y < H;
  const b = {
    ground(x1, x2, top) { for (let x = x1; x <= x2; x++) for (let y = top; y < H; y++) if (inb(x, y)) g[y][x] = '#'; },
    block(x1, y1, x2, y2, ch = '#') { for (let y = y1; y <= y2; y++) for (let x = x1; x <= x2; x++) if (inb(x, y)) g[y][x] = ch; },
    set(x, y, ch) { if (inb(x, y)) g[y][x] = ch; },
    item(x, y, id) { if (inb(x, y)) { g[y][x] = 'i'; items.push({ x, y, id }); } },
    hint(x, y, text) { hints.push({ x, y, text }); },
  };
  spec.build(b);
  const out = Object.assign({}, spec, { h: H, rows: g.map((r) => r.join('')), items, hints });
  delete out.build;
  return out;
}

